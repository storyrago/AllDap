-- 🔴 이 컬럼은 <아직 아무것도 청구하지 않는다.> 요금제 연동 4조각 중 2번이고,
--    4번(청구)이 없기 때문이다. 지금 이 값이 하는 일은 "이 계정이 어느 요금제를 골랐나" 를
--    기억하는 것뿐이다. 화면도 그렇게 안내한다 — 고르면 돈이 나간다고 오해하면 안 된다.
--
-- 왜 users 의 컬럼인가 (별도 subscriptions 테이블이 아니라)
--   지금 필요한 것은 <현재 요금제 하나>뿐이다. 별도 테이블은 "언제부터 언제까지 어느 요금제였나"
--   라는 <이력>을 담기 위한 것인데, 그 이력이 필요해지는 시점은 청구(4번)를 만들 때다.
--   그때는 어차피 청구서·기간·금액을 함께 설계해야 하므로 지금 모양을 미리 잡아둘 근거가 없다.
--   ⚠️ 그래서 이 컬럼은 <지금 시점의 선택>만 안다. 지난달에 무엇이었는지는 알 수 없다.

ALTER TABLE users ADD COLUMN plan VARCHAR(16) NOT NULL DEFAULT 'free';

-- 값을 DB 가 막는다. Java enum 이 이미 값을 좁히지만, 그건 <우리 코드를 거쳐 들어올 때만> 유효하다.
-- SQL 로 직접 고치는 경우(운영 중 수동 조정·마이그레이션 실수)까지 막으려면 제약이 필요하다.
-- ⚠️ 요금제를 추가하려면 이 제약도 새 마이그레이션으로 함께 바꿔야 한다 — 그게 의도다.
--    "화면에만 추가하고 DB 는 잊는" 사고가 나면 저장이 500 으로 실패해 즉시 드러난다.
ALTER TABLE users ADD CONSTRAINT ck_users_plan CHECK (plan IN ('free', 'pro'));
