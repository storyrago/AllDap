"use client";

/**
 * 임베드 위젯(`/w/[publicKey]`)의 에러 경계.
 *
 * ── 🔴 왜 루트 경계로 안 되는가 (PR 리뷰에서 나온 지적) ────────────────────
 * 이 화면은 **고객사 사이트의 iframe 안**에서 그 사이트 방문자가 본다. 우리 사용자가
 * 아니다. 루트 경계(`app/error.tsx`)가 이 자리를 덮으면 두 가지가 잘못된다:
 *
 *   ① **우리 예외 문구가 남의 사이트에 그려진다.** 루트 경계는 단서를 남기려고
 *      `오류 내용: Cannot read properties of undefined...` 를 보여주는데, 그건
 *      <우리에게 문의할 수 있는 사람>에게나 쓸모가 있다. 방문자는 그 문자열로 할 수 있는 게
 *      없고, 고객사 입장에서는 자기 사이트에 남의 스택 문구가 뜬 것이다.
 *   ② **링크가 iframe 을 납치한다.** 루트 경계의 "처음 화면으로"(`/`)를 누르면
 *      고객사 페이지 안의 그 창이 <우리 랜딩>으로 바뀐다. 방문자에게는 뜬금없는 이동이다.
 *
 * 그래서 여기서는 **링크를 두지 않고 내부 정보도 보여주지 않는다.** 방문자가 할 수 있는
 * 유일한 행동인 [다시 시도] 하나만 둔다.
 *
 * ── ⚠️ 앞선 PR 에서 "확인할 수 없어 안 만든다" 고 적었던 것을 정정한다 ──────
 * 그때 근거는 "위젯은 iframe 안에서만 제대로 동작해 깨뜨려 확인할 수 없다" 였다.
 * **틀렸다.** 이 페이지는 직접 열어도 렌더된다(로더가 안 줘서 봇 이름·인사말이 빠질 뿐이고,
 * 그건 `page.tsx` 가 <의도적으로> 그렇게 만든 것이다). 경계를 확인하는 데 필요한 것은
 * "렌더되다 예외가 나는 것" 뿐이라, 직접 열어서 그대로 재볼 수 있다. 실제로 재보고 만들었다.
 *
 * ── 좁은 폭을 신경 쓰는 이유 ────────────────────────────────────────────────
 * 관리자 화면은 데스크톱만 맞추지만(2026-08-17 결정) **위젯은 예외다.** 고객사 사이트에
 * 붙어 방문자가 쓰므로 좁은 창에서 열린다. 그래서 고정 폭을 두지 않고 글자가 접히게 둔다.
 *
 * ── ⚠️ 증상을 가리는 것이지 원인을 고치는 게 아니다 ────────────────────────
 * `app/(dashboard)/error.tsx` 상단 주석과 같다. 경계는 언마운트 범위를 정할 뿐이다.
 */

export default function WidgetError({ reset }: { reset: () => void }) {
  /*
   * `error` prop 을 아예 받지 않는다. 받아두면 "단서니까 보여주자" 는 수정이 언젠가
   * 들어오는데, 이 화면에서는 그게 곧 위 ①번 문제다. 안 받으면 그 실수를 할 수가 없다.
   * (Next 는 `error` 와 `reset` 을 둘 다 넘긴다. 안 쓰는 prop 을 안 적는 것은 자유다)
   */
  return (
    <div className="flex min-h-dvh flex-col items-center justify-center gap-3 px-5 text-center">
      <p className="text-sm font-medium">챗봇을 표시하지 못했습니다</p>
      {/*
        문구에 "잠시 후" 를 넣지 않는다. 시간이 지나면 풀린다는 <근거가 없다>:
        원인이 이 화면의 코드면 내일 열어도 같다. 이 저장소가 반복해 지적한 부류다.
        방문자에게 정직한 안내는 "지금 우리가 아는 것" 까지다:
        다시 시도해볼 수 있고, 안 되면 이 사이트 운영자에게 알리는 것이 유일한 길이다.
      */}
      <p className="text-xs text-muted">
        다시 시도해도 열리지 않으면 이 사이트 운영자에게 알려주세요.
      </p>
      <button
        type="button"
        onClick={reset}
        className="mt-1 rounded-md bg-foreground px-4 py-2 text-xs font-medium text-surface"
      >
        다시 시도
      </button>
    </div>
  );
}
